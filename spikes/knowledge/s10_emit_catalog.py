"""Writes the data block of services/localmodels/catalog.py from out/catalog.json, so no hash is
ever typed by hand. Run: uv run s10_emit_catalog.py > out/catalog_data.py"""

import json
import sys

sys.stdout.reconfigure(encoding="utf-8")
cat = json.load(open("out/catalog.json"))
print("# --- generated by spikes/knowledge/s10_emit_catalog.py: do not edit by hand")
for key, e in cat.items():
    var = key.upper().replace("-", "_").replace(".", "_")
    print(f'{var}_REPO = "{e["repo"]}"')
    print(f'{var}_REVISION = "{e["revision"]}"')
    for f in e["files"]:
        const = f"{var}_{f['name'].upper().replace('/', '_').replace('.', '_').replace('-', '_')}"
        print(f'{const} = ({f["size"]}, "{f["sha256"]}")')
