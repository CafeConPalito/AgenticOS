"""Prints the phase 16 pins (repository revision, size, SHA-256) from the files the spikes
downloaded, so no hash is ever typed by hand. Append the output to
backend/src/agentic_os/services/localmodels/_pins.py.

    uv run python dictation/s12_emit_pins.py >> backend/src/agentic_os/services/localmodels/_pins.py
"""

import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).parent
WHISPER_REVISION = "5359861c739e955e79d9a303bcbc70fb988958b1"  # ggerganov/whisper.cpp
VAD_REVISION = "9ffd54a1e1ee413ddf265af9913beaf518d1639b"  # ggml-org/whisper-vad

FILES = {
    "WHISPER_BASE": HERE / "models" / "ggml-base.bin",
    "WHISPER_SMALL_Q5": HERE / "models" / "ggml-small-q5_1.bin",
    "WHISPER_TURBO_Q5": HERE / "models" / "ggml-large-v3-turbo-q5_0.bin",
    "WHISPER_VAD": HERE / "models" / "ggml-silero-v5.1.2.bin",
    "WHISPER_CPP_ENGINE": HERE / "engine" / "whisper-bin-x64.zip",
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(1 << 20):
            digest.update(chunk)
    return digest.hexdigest()


sys.stdout.reconfigure(encoding="utf-8")
print("# --- phase 16, generated by spikes/dictation/s12_emit_pins.py: do not edit by hand")
print('WHISPER_REPO = "ggerganov/whisper.cpp"')
print(f'WHISPER_REVISION = "{WHISPER_REVISION}"')
print('WHISPER_VAD_REPO = "ggml-org/whisper-vad"')
print(f'WHISPER_VAD_REVISION = "{VAD_REVISION}"')
for name, path in FILES.items():
    print(f'{name} = ({path.stat().st_size}, "{sha256(path)}")')
