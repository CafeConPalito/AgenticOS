AGENT_BLOCK = re.compile(r"^### (\d{4}-\d{2}-\d{2} \d{2}:\d{2}) · (.+)$", re.MULTILINE)


def split_memory(memory: str) -> list[tuple[str, str, datetime | None, str]]:
    """(author_kind, author_name, written_at, text) for each note of an old memory text."""
    notes: list[tuple[str, str, datetime | None, str]] = []
    matches = list(AGENT_BLOCK.finditer(memory))
    head = memory[: matches[0].start()] if matches else memory
    if head.strip():
        notes.append(("user", "", None, head.strip()))
    for i, match in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(memory)
        text = memory[match.end() : end].strip()
        if not text:
            continue
        # The stamp was written in local time (manager.write_project_memory).
        local = datetime.strptime(match.group(1), "%Y-%m-%d %H:%M").astimezone()
        notes.append(("agent", match.group(2).strip(), local.astimezone(UTC), text))
    return notes


def join_notes(rows: list[tuple[str, str, datetime, str]]) -> str:
    """The inverse, for the downgrade: (author_kind, author_name, created_at) + text."""
    blocks = []
    for kind, name, at, text in rows:
        if kind == "agent":
            stamp = at.replace(tzinfo=UTC).astimezone().strftime("%Y-%m-%d %H:%M")
            blocks.append(f"### {stamp} · {name}\n{text.strip()}")
        else:
            blocks.append(text.strip())
    return "\n\n".join(blocks)


