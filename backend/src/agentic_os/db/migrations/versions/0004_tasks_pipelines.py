def _memory_to_notes() -> None:
    conn = op.get_bind()
    now = datetime.now(UTC)
    rows = []
    for project_id, memory in conn.execute(sa.text("SELECT id, memory FROM projects")):
        notes = split_memory(memory or "")
        # The user's text came first: it keeps its place before the oldest agent note.
        dated = [at for _, _, at, _ in notes if at is not None]
        before_all = min(dated) - timedelta(minutes=1) if dated else now
        for kind, name, at, text in notes:
            agent_id = None
            if kind == "agent":
                agent_id = conn.execute(
                    sa.text("SELECT id FROM agents WHERE name = :name LIMIT 1"), {"name": name}
                ).scalar()
            stamp = at or before_all
            rows.append(
                {
                    "id": str(uuid.uuid4()),
                    "project_id": project_id,
                    "author_kind": kind,
                    "author_name": name,
                    "agent_id": agent_id,
                    "text": text,
                    "created_at": stamp,
                    "updated_at": stamp,
                }
            )
    if rows:
        op.bulk_insert(NOTES, rows)


def _notes_to_memory() -> None:
    conn = op.get_bind()
    by_project: dict[str, list] = {}
    query = sa.select(
        NOTES.c.project_id,
        NOTES.c.author_kind,
        NOTES.c.author_name,
        NOTES.c.created_at,
        NOTES.c.text,
    ).order_by(NOTES.c.created_at)
    for project_id, kind, name, at, text in conn.execute(query):
        by_project.setdefault(project_id, []).append((kind, name, at, text))
    for project_id, rows in by_project.items():
        conn.execute(
            sa.text("UPDATE projects SET memory = :memory WHERE id = :id"),
            {"memory": join_notes(rows), "id": project_id},
        )
