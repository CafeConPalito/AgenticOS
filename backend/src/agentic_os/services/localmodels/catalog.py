BY_ID: Mapping[str, CatalogEntry] = MappingProxyType({e.id: e for e in CATALOG})


def entry(entry_id: str) -> CatalogEntry | None:
    return BY_ID.get(entry_id)


def of_kind(kind: str) -> list[CatalogEntry]:
    return [e for e in CATALOG if e.kind == kind]


def default_of(kind: str) -> CatalogEntry | None:
    return next((e for e in CATALOG if e.kind == kind and e.default), None)
