"""What can be downloaded: the local models and engines the knowledge library may use.

Nothing here ships in the installer. Every file is pinned (an exact revision of the repository
or release, its size and its SHA-256, all measured in the phase 14 spikes) so a download is
either exactly what was tested or it is rejected. Adding a model is adding an entry.
The Hugging Face data lives in `_pins.py`, generated by `spikes/knowledge/s10_emit_catalog.py`.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field
from types import MappingProxyType
from typing import Any

from agentic_os.services.localmodels import _pins as pin

EMBEDDING = "embedding"  # turns text into vectors, for the search by meaning
OCR = "ocr"  # reads the text of pictures and scanned pages
VISION = "vision"  # describes pictures (served by llama.cpp)
SPEECH = "speech"  # turns the user's voice into text (Whisper, served by whisper.cpp)
ENGINE = "engine"  # a program the models run on (llama.cpp, whisper.cpp)
KINDS = (EMBEDDING, OCR, VISION, SPEECH, ENGINE)


@dataclass(frozen=True)
class RemoteFile:
    name: str  # where it goes inside the entry's folder
    size: int
    sha256: str
    urls: tuple[str, ...]  # tried in order


@dataclass(frozen=True)
class CatalogEntry:
    id: str
    kind: str
    title: str
    license: str
    files: tuple[RemoteFile, ...]
    default: bool = False  # the one used when the user has not chosen
    needs_account: bool = False  # a Hugging Face token is required to download it
    platforms: tuple[str, ...] = ("win32",)
    # How to use it once downloaded: dimensions, prefixes, which file is the model…
    usage: Mapping[str, Any] = field(default_factory=lambda: MappingProxyType({}))
    # An engine arrives as an archive: the name of the file in `files` to unpack.
    unpack: str | None = None
    # Shipped inside the installer: nothing to download where the build includes it
    # (see store.bundled_folder). Everywhere else it is downloaded like any other model.
    bundled: bool = False

    @property
    def size(self) -> int:
        return sum(f.size for f in self.files)

    @property
    def folder(self) -> str:
        return "engines" if self.kind == ENGINE else "models"


def _hf(repo: str, revision: str, name: str, pinned: tuple[int, str]) -> RemoteFile:
    size, sha256 = pinned
    url = f"https://huggingface.co/{repo}/resolve/{revision}/{name}"
    return RemoteFile(name, size, sha256, (url,))


def _ocr(path: str, name: str, size: int, sha256: str) -> RemoteFile:
    base = "https://www.modelscope.cn/models/RapidAI/RapidOCR/resolve/v3.10.0/onnx"
    return RemoteFile(name, size, sha256, (f"{base}/{path}",))


def _usage(**values: Any) -> Mapping[str, Any]:
    return MappingProxyType(values)


def _vision(entry_id: str, title: str, repo: str, revision: str, model, projector, default=False):
    (model_name, model_pin), (projector_name, projector_pin) = model, projector
    return CatalogEntry(
        entry_id,
        VISION,
        title,
        "apache-2.0",
        (
            _hf(repo, revision, model_name, model_pin),
            _hf(repo, revision, projector_name, projector_pin),
        ),
        default=default,
        usage=_usage(model=model_name, projector=projector_name),
    )


def _speech(
    entry_id: str, title: str, model_name: str, model_pin, speed: str, quality: str, default=False
):
    """A Whisper model for dictation. The voice-activity model (Silero, under 1 MB) comes with
    every one: it is what turns silence into an empty text instead of an invented one (S3)."""
    return CatalogEntry(
        entry_id,
        SPEECH,
        title,
        "mit",
        (
            _hf(pin.WHISPER_REPO, pin.WHISPER_REVISION, model_name, model_pin),
            _hf(pin.WHISPER_VAD_REPO, pin.WHISPER_VAD_REVISION, VAD_FILE, pin.WHISPER_VAD),
        ),
        default=default,
        usage=_usage(model=model_name, vad=VAD_FILE, speed=speed, quality=quality),
    )


